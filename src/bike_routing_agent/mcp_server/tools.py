class ApiError(Exception):
    """The API could not be reached or refused the request; the message is for the agent."""


def check_arguments(schema: dict[str, Any], arguments: dict[str, Any]) -> list[str]:
    """What is wrong with ``arguments`` against the (small) subset of JSON Schema the tools use."""
    problems: list[str] = []
    properties = schema.get("properties", {})
    for name in schema.get("required", []):
        if name not in arguments:
            problems.append(f"{name} is required")
    for name, value in arguments.items():
        spec = properties.get(name)
        if spec is None:
            problems.append(f"{name} is not a parameter of this tool")
            continue
        problem = _check_value(name, spec, value)
        if problem:
            problems.append(problem)
    return problems


def _check_value(name: str, spec: dict[str, Any], value: Any) -> str | None:
    kind = spec.get("type")
    if kind == "string":
        if not isinstance(value, str) or not value.strip():
            return f"{name} must be a non-empty string"
        if "enum" in spec and value not in spec["enum"]:
            return f"{name} must be one of {', '.join(spec['enum'])}"
    elif kind == "boolean":
        if not isinstance(value, bool):
            return f"{name} must be true or false"
    elif kind in ("number", "integer"):
        if isinstance(value, bool) or not isinstance(value, int | float):
            return f"{name} must be a number"
        if kind == "integer" and int(value) != value:
            return f"{name} must be a whole number"
        if "minimum" in spec and value < spec["minimum"]:
            return f"{name} must be at least {spec['minimum']}"
        if "maximum" in spec and value > spec["maximum"]:
            return f"{name} must be at most {spec['maximum']}"
        if "exclusiveMinimum" in spec and value <= spec["exclusiveMinimum"]:
            return f"{name} must be more than {spec['exclusiveMinimum']}"
    elif kind == "array":
        if not isinstance(value, list):
            return f"{name} must be a list"
        item = spec.get("items", {})
        for entry in value:
            problem = _check_value(f"{name} item", item, entry)
            if problem:
                return problem
    return None


def place(text: str) -> str | dict[str, float]:
    """A place as the API takes it: a name stays a string, ``lat,lon`` becomes a coordinate."""
    match = COORDINATE.match(text)
    if match:
        lat, lon = float(match.group(1)), float(match.group(2))
        if -90 <= lat <= 90 and -180 <= lon <= 180:
            return {"lon": lon, "lat": lat}
    return text.strip()


def _round(value: float | None, digits: int = 1) -> float | None:
    return None if value is None else round(value, digits)


def candidate_summary(candidate: dict[str, Any]) -> dict[str, Any]:
    """One route as facts (no geometry): what the page and the chat show for it."""
    metrics = candidate.get("metrics") or {}
    weather = candidate.get("weather") or {}
    summary: dict[str, Any] = {
        "rank": candidate.get("rank"),
        "engine": candidate.get("provider"),
        "profile": candidate.get("provider_profile"),
        "distance_km": _round((metrics.get("distance_m") or 0) / 1000),
        "duration_min": _round(
            (metrics["duration_s"] / 60) if metrics.get("duration_s") else None, 0
        ),
        "ascent_m": _round(metrics.get("ascent_m"), 0),
        "descent_m": _round(metrics.get("descent_m"), 0),
        "surface": surface_text(metrics),
        "surface_shares": {k: round(v, 3) for k, v in surface_shares(metrics).items()},
        "traffic": traffic_text(metrics),
        "traffic_shares": {
            k: round(v, 3) for k, v in (metrics.get("traffic_shares") or {}).items()
        },
        "pros": list(candidate.get("pros") or []),
        "cons": list(candidate.get("cons") or []),
        "compared_with_best": candidate.get("rank_rationale"),
        "warnings": list(candidate.get("warnings") or []),
        "forecast": bool(weather),
    }
    return summary


def _messages(items: list[Any] | None) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    for item in items or []:
        if isinstance(item, dict):
            out.append({"code": item.get("code"), "message": item.get("message")})
        else:
            out.append({"code": None, "message": str(item)})
    return out


class BikeRouterTools:
    """The four tools, answering from the API at ``api_url``."""

    def __init__(
        self,
        api_url: str,
        *,
        client: httpx.Client | None = None,
        timeout_s: float = 300.0,
        max_plans: int = MAX_PLANS,
    ) -> None:
        self._api = api_url.rstrip("/")
        self._client = client or httpx.Client(timeout=timeout_s)
        self._plans: OrderedDict[str, dict[str, Any]] = OrderedDict()
        self._max_plans = max_plans
        self._counter = 0
        self._handlers = {
            "plan_route": self._plan_route,
            "explain_route": self._explain_route,
            "route_weather": self._route_weather,
            "sights_along_route": self._sights_along_route,
        }

    def definitions(self) -> list[dict[str, Any]]:
        return TOOLS

    def call(self, name: str, arguments: dict[str, Any]) -> tuple[dict[str, Any], bool]:
        handler = self._handlers[name]  # KeyError: no such tool (a protocol error)
        schema = next(t["inputSchema"] for t in TOOLS if t["name"] == name)
        problems = check_arguments(schema, arguments)
        if problems:
            return {"error": "invalid arguments", "problems": problems}, True
        try:
            return handler(arguments), False
        except ApiError as exc:
            return {"error": str(exc)}, True
        except LookupError as exc:  # an unknown plan_ref or rank
            return {"error": str(exc.args[0] if exc.args else exc)}, True

    # ------------------------------------------------------------------------------ the API

    def _request(self, method: str, path: str, body: dict[str, Any]) -> dict[str, Any]:
        try:
            response = self._client.request(method, f"{self._api}{path}", json=body)
        except httpx.TimeoutException as exc:
            raise ApiError(f"the pyBikeRouter API at {self._api} did not answer in time") from exc
        except httpx.HTTPError as exc:
            raise ApiError(f"cannot reach the pyBikeRouter API at {self._api}: {exc}") from exc
        if response.status_code == 422:
            raise ApiError("the request was refused: " + _detail(response))
        if response.status_code >= 400:
            raise ApiError(f"the API answered HTTP {response.status_code}: {_detail(response)}")
        try:
            data = response.json()
        except ValueError as exc:
            raise ApiError("the API sent something that is not JSON") from exc
        if not isinstance(data, dict):
            raise ApiError("the API sent an unexpected answer")
        return data

    # ------------------------------------------------------------------------------ plan_route

    def _plan_route(self, args: dict[str, Any]) -> dict[str, Any]:
        loop = bool(args.get("loop"))
        if loop and "target_distance_km" not in args:
            raise ApiError("a loop needs target_distance_km")
        if not loop and "destination" not in args:
            raise ApiError("give a destination, or loop=true with target_distance_km")
        if loop and "destination" in args:
            raise ApiError("a loop has no destination: leave it out")
        constraints: dict[str, Any] = {
            key: args[key]
            for key in (
                "bike_type",
                "target_distance_km",
                "max_distance_km",
                "max_ascent_m",
                "prefer_surfaces",
                "avoid_surfaces",
                "avoid_high_traffic_roads",
                "avoid_ferries",
            )
            if key in args
        }
        if loop:
            constraints["return_to_origin"] = True
        body: dict[str, Any] = {
            "origin": place(args["origin"]),
            "via": [place(v) for v in args.get("via", [])],
            "constraints": constraints,
        }
        if not loop:
            body["destination"] = place(args["destination"])
        for key in ("departure_time", "max_alternatives"):
            if key in args:
                body[key] = args[key]
        if args.get("sight_stops"):
            body["poi_stops"] = {"count": args["sight_stops"]}
        plan = self._request("POST", "/v1/route/plan", body)
        return self._plan_summary(plan)

    def _plan_summary(self, plan: dict[str, Any]) -> dict[str, Any]:
        status = plan.get("status")
        out: dict[str, Any] = {"status": status, "notes": _messages(plan.get("errors"))}
        if status == "awaiting_clarification":
            out["clarification"] = [
                {
                    "field": group.get("field"),
                    "candidates": [
                        {
                            "label": c.get("label"),
                            "coordinates": _latlon(c.get("coordinate")),
                        }
                        for c in (group.get("candidates") or [])[:5]
                    ],
                    "hint": group.get("hint"),
                }
                for group in plan.get("clarification") or []
            ]
            out["next"] = "call plan_route again with the chosen candidate's coordinates"
            return out
        if status != "ready":
            return out
        self._counter += 1
        ref = f"plan-{self._counter}"
        self._plans[ref] = plan
        while len(self._plans) > self._max_plans:
            self._plans.popitem(last=False)
        candidates = plan.get("candidates") or [plan.get("route")]
        summaries = [candidate_summary(c) for c in candidates if c]
        out.update(
            {
                "plan_ref": ref,
                "explanation": plan.get("explanation"),
                "route": summaries[0] if summaries else None,
                "alternatives": summaries[1:],
                "sight_stops": [
                    {"name": s.get("name"), "category": s.get("category"), "fame": s.get("fame")}
                    for s in plan.get("poi_stops") or []
                ],
                "files": {
                    key.removesuffix("_url"): self._api + url
                    for key, url in (plan.get("artifacts") or {}).items()
                    if isinstance(url, str) and url.startswith("/")
                },
            }
        )
        return out

    # ------------------------------------------------------------------------------ follow-ups

    def _stored(self, args: dict[str, Any]) -> tuple[dict[str, Any], dict[str, Any]]:
        ref = args["plan_ref"]
        plan = self._plans.get(ref)
        if plan is None:
            raise LookupError(
                f"unknown plan_ref {ref!r}: plan the route again (plans are kept in memory)"
            )
        rank = args.get("rank", 1)
        candidates = plan.get("candidates") or [plan.get("route")]
        for candidate in candidates:
            if candidate and (candidate.get("rank") or 1) == rank:
                return plan, candidate
        raise LookupError(f"plan {ref} has {len(candidates)} route(s): there is no rank {rank}")

    def _explain_route(self, args: dict[str, Any]) -> dict[str, Any]:
        plan, candidate = self._stored(args)
        summary = candidate_summary(candidate)
        if summary["rank"] in (None, 1):
            summary["explanation"] = plan.get("explanation")
        summary["plan_ref"] = args["plan_ref"]
        return summary

    def _route_weather(self, args: dict[str, Any]) -> dict[str, Any]:
        plan, candidate = self._stored(args)
        weather = candidate.get("weather")
        if not weather:
            return {
                "available": False,
                "reason": plan.get("weather_status")
                or "no forecast for this route (switched off, unavailable, or too far ahead)",
            }
        out = {
            "available": True,
            **{
                key: weather.get(key)
                for key in (
                    "provider",
                    "attribution",
                    "departure",
                    "arrival",
                    "summary",
                    "daylight",
                    "wind_effect",
                    "advisories",
                    "suggested_departure",
                    "departure_options",
                )
            },
        }
        if args.get("detail"):
            out["samples"] = weather.get("samples")
        return out

    def _sights_along_route(self, args: dict[str, Any]) -> dict[str, Any]:
        _, candidate = self._stored(args)
        coordinates = [
            [position[0], position[1]]
            for position in (candidate.get("geometry_geojson") or {}).get("coordinates") or []
        ]
        if len(coordinates) > MAX_ROUTE_POINTS:  # a very long route: every n-th point is enough
            step = -(-len(coordinates) // MAX_ROUTE_POINTS)
            coordinates = coordinates[::step] + [coordinates[-1]]
        kind = args.get("kind", "sight")
        body: dict[str, Any] = {"coordinates": coordinates}
        categories = args.get("categories") or (list(SIGHT_KEYS) if kind == "sight" else None)
        if categories:
            body["categories"] = categories
        if "buffer_m" in args:
            body["buffer_m"] = args["buffer_m"]
        found = self._request("POST", "/v1/pois/along-route", body)
        pois = [p for p in found.get("pois") or [] if p.get("kind") == kind]
        pois.sort(
            key=lambda p: -(p.get("fame") or 0) if kind == "sight" else p.get("along_route_km") or 0
        )
        shown = pois[: args.get("limit", 15)]
        return {
            "kind": kind,
            "count": len(shown),
            "more_found": len(pois) - len(shown),
            "fame_status": found.get("fame_status"),
            "truncated": bool(found.get("truncated")),
            "places": [
                {
                    key: p.get(key)
                    for key in (
                        "name",
                        "category",
                        "fame",
                        "distance_from_route_m",
                        "along_route_km",
                        "lat",
                        "lon",
                        "wikipedia",
                        "wikidata",
                        "website",
                        "opening_hours",
                    )
                }
                for p in shown
            ],
        }


def _latlon(coordinate: Any) -> str | None:
    if isinstance(coordinate, dict) and "lat" in coordinate and "lon" in coordinate:
        return f"{coordinate['lat']},{coordinate['lon']}"
    return None


def _detail(response: httpx.Response) -> str:
    try:
        body = response.json()
    except ValueError:
        return response.text[:200]
    detail = body.get("detail") if isinstance(body, dict) else None
    if isinstance(detail, list):
        return "; ".join(
            f"{'.'.join(str(p) for p in d.get('loc', []))}: {d.get('msg')}"
            for d in detail
            if isinstance(d, dict)
        )
    return str(detail or body)[:300]
