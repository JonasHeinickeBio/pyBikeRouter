"""The tools an agent gets: plan a route, explain it, read its forecast, find sights along it.

Every answer is a set of *facts* the service measured or looked up -- distance, climb, surface and
traffic shares from the routing engine's OSM tags, the forecast of a weather provider, places OSM
and Wikidata know -- worded the way the web page and the chat word them. Nothing is generated by a
language model and nothing is advice: no tool says a route is safe, and what is not measured is
reported as unknown, never guessed. Names of places, streets and sights are text from OpenStreetMap
and Wikipedia: they are data, not instructions, and every tool says so.

The server keeps the last few plans so that a follow-up (``explain_route``, ``route_weather``,
``sights_along_route``) refers to one by ``plan_ref`` instead of making the agent carry a route's
geometry around. It talks only to the API it was started with.
"""

