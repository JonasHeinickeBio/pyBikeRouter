"""``bike-router completion`` group: tab completion for bash, zsh and fish.

The scripts are generated from the parser itself, so they list every group, command and option
that exists today (and the values an option accepts, like ``--format json|text``) and never go
stale. Nothing is installed or written: the script is printed, and the person decides where it
goes (``docs/cli.md`` has the one-liners).
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass, field
from typing import IO

SHELLS = ("bash", "zsh", "fish")


@dataclass
class Node:
    """One word of the command line: the program, a group or a command."""

    path: tuple[str, ...]
    help: str = ""
    children: dict[str, Node] = field(default_factory=dict)
    options: list[str] = field(default_factory=list)
    choices: dict[str, list[str]] = field(default_factory=dict)  # option -> values it takes


def _subparsers(parser: argparse.ArgumentParser) -> argparse._SubParsersAction | None:
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return action
    return None


def command_tree(parser: argparse.ArgumentParser, path: tuple[str, ...] = ()) -> Node:
    """The groups, commands and options of ``parser``, as a tree."""
    node = Node(path=path)
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            continue
        for option in action.option_strings:
            if option.startswith("-"):
                node.options.append(option)
                if action.choices:
                    node.choices[option] = [str(c) for c in action.choices]
    sub = _subparsers(parser)
    if sub is not None:
        helps = {a.dest: a.help or "" for a in sub._choices_actions}
        for name, child in sub.choices.items():
            built = command_tree(child, (*path, name))
            built.help = helps.get(name, "")
            node.children[name] = built
    return node


def _walk(node: Node) -> list[Node]:
    found = [node]
    for child in node.children.values():
        found.extend(_walk(child))
    return found


def _quote(text: str) -> str:
    return "'" + text.replace("'", "'\\''") + "'"


def bash_script(root: Node, program: str = "bike-router") -> str:
    """A bash completion function (zsh uses it through ``bashcompinit``)."""
    nodes = _walk(root)
    function = "_" + program.replace("-", "_")
    words = [
        f"    {_quote(' '.join(n.path))}) echo {_quote(' '.join([*n.children, *n.options]))} ;;"
        for n in nodes
    ]
    values = [
        f"    {_quote(' '.join(n.path) + (' ' if n.path else '') + opt)}) "
        f"echo {_quote(' '.join(vals))} ;;"
        for n in nodes
        for opt, vals in n.choices.items()
    ]
    lines = [
        f"# bash completion for {program} (generated by '{program} completion bash')",
        f"{function}_words() {{",
        '  case "$1" in',
        *words,
        "  esac",
        "}",
        f"{function}_values() {{",
        '  case "$1" in',
        *values,
        "  esac",
        "}",
        f"{function}() {{",
        "  local cur prev node key i candidates",
        '  cur="${COMP_WORDS[COMP_CWORD]}"',
        '  prev="${COMP_WORDS[COMP_CWORD-1]}"',
        '  node=""',
        "  for ((i = 1; i < COMP_CWORD; i++)); do",
        '    key="${node:+$node }${COMP_WORDS[i]}"',
        f'    if [ -n "$({function}_words "$key")" ]; then node="$key"; fi',
        "  done",
        f'  candidates="$({function}_values "${{node:+$node }}$prev")"',
        '  if [ -z "$candidates" ]; then',
        f'    candidates="$({function}_words "$node")"',
        '    case "$cur" in',
        "      -*) ;;",
        '      *) candidates="$(for w in $candidates; do case "$w" in -*) ;; *) echo "$w" ;; '
        'esac; done)" ;;',
        "    esac",
        "  fi",
        '  COMPREPLY=($(compgen -W "$candidates" -- "$cur"))',
        "}",
        f"complete -o default -F {function} {program}",
    ]
    return "\n".join(lines) + "\n"


def zsh_script(root: Node, program: str = "bike-router") -> str:
    """zsh reads the bash function through its own ``bashcompinit``."""
    head = [
        f"# zsh completion for {program} (generated by '{program} completion zsh')",
        "autoload -U +X compinit && compinit",
        "autoload -U +X bashcompinit && bashcompinit",
    ]
    return "\n".join(head) + "\n" + bash_script(root, program)


def fish_script(root: Node, program: str = "bike-router") -> str:
    """fish completions: groups, then the commands of the group typed, then their options."""
    lines = [f"# fish completion for {program} (generated by '{program} completion fish')"]
    for option in root.options:
        flag = "-l " + option[2:] if option.startswith("--") else "-s " + option[1:]
        lines.append(f"complete -c {program} -f {flag}")
    for name, group in root.children.items():
        lines.append(
            f"complete -c {program} -f -n '__fish_use_subcommand' -a {name} -d {_quote(group.help)}"
        )
        for option in group.options:
            flag = "-l " + option[2:] if option.startswith("--") else "-s " + option[1:]
            lines.append(f"complete -c {program} -f -n '__fish_seen_subcommand_from {name}' {flag}")
        for command, node in group.children.items():
            seen = f"__fish_seen_subcommand_from {name}; and not __fish_seen_subcommand_from "
            others = " ".join(group.children)
            lines.append(
                f"complete -c {program} -f -n '{seen}{others}' -a {command} -d {_quote(node.help)}"
            )
            for option in node.options:
                flag = "-l " + option[2:] if option.startswith("--") else "-s " + option[1:]
                values = node.choices.get(option)
                extra = f" -x -a {_quote(' '.join(values))}" if values else ""
                lines.append(
                    f"complete -c {program} -f -n "
                    f"'__fish_seen_subcommand_from {name}; and __fish_seen_subcommand_from "
                    f"{command}' {flag}{extra}"
                )
    return "\n".join(lines) + "\n"


def add_parser(subparsers: argparse._SubParsersAction) -> argparse.ArgumentParser:
    group = subparsers.add_parser(
        "completion",
        help="tab completion for bash, zsh and fish",
        description="Print a completion script for your shell (see docs/cli.md for where it goes).",
    )
    sub = group.add_subparsers(dest="command", metavar="<shell>")
    if sub is None:  # pragma: no cover - argparse types only
        raise RuntimeError("subparsers are required")
    for shell in SHELLS:
        sub.add_parser(shell, help=f"the {shell} completion script")
    return group


def run(args: argparse.Namespace, stdout: IO[str], stderr: IO[str]) -> int:
    from bike_routing_agent.cli.main import build_parser

    if args.command not in SHELLS:
        print(f"unknown shell: {args.command}", file=stderr)
        return 2
    root = command_tree(build_parser())
    script = {"bash": bash_script, "zsh": zsh_script, "fish": fish_script}[args.command]
    stdout.write(script(root))
    return 0
