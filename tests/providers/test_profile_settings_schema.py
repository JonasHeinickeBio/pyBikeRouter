"""The LinkML schema of the profile settings, the models generated from it, and what reads them."""

from __future__ import annotations

from pathlib import Path

import pytest
from pydantic import ValidationError

from bike_routing_agent.providers import brouter_params as params
from bike_routing_agent.providers import profile_settings_model as models

PROVIDERS = Path(__file__).resolve().parents[2] / "src" / "bike_routing_agent" / "providers"
SCHEMA = PROVIDERS / "profile_settings.linkml.yaml"
GENERATED = PROVIDERS / "profile_settings_model.py"
HEADER_LINES = 2  # the "GENERATED by ..." note scripts/gen_profile_settings.sh puts on top


def _schema() -> dict:
    yaml = pytest.importorskip("yaml")
    return yaml.safe_load(SCHEMA.read_text())


def test_the_committed_models_are_what_the_schema_generates(monkeypatch):
    """Run where linkml is importable (``uvx --from linkml``, or after ``pip install linkml``)."""
    pydanticgen = pytest.importorskip("linkml.generators.pydanticgen")
    monkeypatch.chdir(PROVIDERS)  # the generator records the schema's path: keep it relative
    fresh = pydanticgen.PydanticGenerator(SCHEMA.name).serialize()
    committed = "\n".join(GENERATED.read_text().splitlines()[HEADER_LINES:])
    assert committed.rstrip() == fresh.rstrip(), "run scripts/gen_profile_settings.sh"


def test_every_profile_class_in_the_schema_is_mapped_and_every_mapped_class_is_in_it():
    classes = _schema()["classes"]
    concrete = {name for name, spec in classes.items() if not spec.get("mixin")}
    mapped = {model.__name__ for model in params.PROFILE_MODELS.values()}
    assert mapped == concrete


def test_every_slot_of_the_schema_is_used_by_some_profile():
    slots = set(_schema()["slots"])
    used = {name for names in params.PROFILE_SETTINGS.values() for name in names}
    assert used == slots


def test_every_slot_has_a_meaning_and_numbers_have_a_range():
    for name, slot in _schema()["slots"].items():
        assert slot.get("description"), name
        if slot["range"] == "float":
            assert slot["minimum_value"] < slot["maximum_value"], name
        else:
            assert slot["range"] == "boolean", name


def test_the_generated_models_need_nothing_but_pydantic():
    source = GENERATED.read_text()
    assert "linkml_runtime" not in source and "import linkml" not in source


def test_each_setting_is_read_from_the_model_with_its_range_and_group():
    spec = params.PROFILE_SPECS["custom_touring-v1"]
    assert spec["uphillcost"].kind == "number" and spec["uphillcost"].range_text == "0..200"
    assert spec["uphillcost"].group == "climbing" and spec["uphillcost"].affects == "route"
    assert spec["consider_noise"].kind == "flag" and spec["consider_noise"].range_text == "on/off"
    assert spec["bikerPower"].group == "rider" and spec["bikerPower"].affects == "time"
    assert spec["avoid_unsafe"].group == "cycle routes"
    assert spec["unpavedPenalty"].range_text == "1..10"
    assert spec["S_C_x"].range_text == "0.05..1.5"
    assert "drag" in spec["S_C_x"].meaning


def test_a_setting_has_the_same_type_and_range_in_every_profile():
    seen: dict[str, tuple] = {}
    for specs in params.PROFILE_SPECS.values():
        for name, setting in specs.items():
            key = (setting.kind, setting.low, setting.high, setting.meaning)
            assert seen.setdefault(name, key) == key, name


def test_strict_validation_accepts_a_good_set_and_names_what_is_wrong():
    assert params.validate("custom_touring-v1", {"uphillcost": 120, "consider_noise": True}) == {
        "uphillcost": 120.0,
        "consider_noise": True,
    }
    with pytest.raises(ValidationError) as error:
        params.validate("custom_touring-v1", {"uphilcost": 120, "totalMass": 5000})
    found = params.problems(error.value, "custom_touring-v1")
    assert any(
        "'uphilcost' is not a setting of custom_touring-v1 (did you mean 'uphillcost'?)" in f
        for f in found
    )
    assert any(f.startswith("totalMass:") and "less than or equal to 300" in f for f in found)


def test_strict_validation_of_a_profile_without_settings_is_a_value_error():
    with pytest.raises(ValueError, match="mtb has no per-request settings"):
        params.validate("mtb", {"uphillcost": 1})


def test_describe_lists_the_settings_and_carries_a_json_schema():
    info = params.describe("custom_gravel-v2")
    names = [s["name"] for s in info["settings"]]
    assert "prefer_unpaved_paths" in names and "uphillcost" not in names
    mass = next(s for s in info["settings"] if s["name"] == "totalMass")
    assert mass == {
        "name": "totalMass",
        "type": "number",
        "group": "rider",
        "affects": "time",
        "meaning": "bike and rider together, in kg",
        "minimum": 20,
        "maximum": 300,
    }
    assert info["json_schema"]["additionalProperties"] is False
    assert info["json_schema"]["properties"]["totalMass"]["anyOf"][0]["maximum"] == 300
    assert params.describe("mtb") == {"profile": "mtb", "settings": [], "json_schema": None}


def test_the_generated_classes_forbid_unknown_names_and_check_ranges():
    with pytest.raises(ValidationError):
        models.GravelV2(uphillcost=1)  # not a gravel setting
    with pytest.raises(ValidationError):
        models.GravelV2(totalMass=1)
    assert models.GravelV2(prefer_unpaved_paths=True).model_dump(exclude_none=True) == {
        "prefer_unpaved_paths": True
    }


def test_strict_validation_refuses_a_boolean_for_a_number_like_the_request_does():
    with pytest.raises(ValueError, match="uphillcost needs a number"):
        params.validate("custom_touring-v1", {"uphillcost": True})
    assert params.resolve("custom_touring-v1", {"uphillcost": True}).values == {}
