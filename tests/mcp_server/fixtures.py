from __future__ import annotations

from typing import Any


def candidate(rank: int, profile: str, distance_m: float, **extra: Any) -> dict[str, Any]:
    return {
        "provider": "brouter",
        "provider_profile": profile,
        "rank": rank,
        "score": 0.9 - rank / 10,
        "geometry_geojson": {
            "type": "LineString",
            "coordinates": [[10.5, 52.2, 80.0], [10.55, 52.25, 90.0], [10.6, 52.3, 85.0]],
        },
        "metrics": {
            "distance_m": distance_m,
            "duration_s": distance_m / 4.5,
            "ascent_m": 160.4,
            "descent_m": 150.0,
            "engine_surface_shares": {"paved": 0.6, "unpaved": 0.3, "unknown": 0.1},
            "traffic_shares": {"quiet": 0.7, "off_road": 0.3},
        },
        "pros": [f"pro {rank}"],
        "cons": [f"con {rank}"],
        "rank_rationale": None if rank == 1 else f"rank {rank}: 2.0 km longer than rank 1",
        "warnings": [],
        "weather": None,
        "raw_provider_response": None,
        **extra,
    }


