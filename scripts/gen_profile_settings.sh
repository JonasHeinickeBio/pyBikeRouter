#!/usr/bin/env bash
# Regenerate providers/profile_settings_model.py from the LinkML schema next to it.
# The generated pydantic models need nothing but pydantic at runtime; LinkML is only used here
# (run through uvx, so it is not a dependency of the project):
#
#   scripts/gen_profile_settings.sh
#
# tests/providers/test_profile_settings_schema.py fails when the committed file is out of date
# (it runs when `linkml` is importable, i.e. under `uvx --from linkml ...` or after pip install).
set -euo pipefail

cd "$(dirname "$0")/../src/bike_routing_agent/providers"
out=profile_settings_model.py
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

# pinned: another LinkML version may generate different code, and CI compares the result
uvx --python 3.12 --from "linkml==1.12.1" gen-pydantic profile_settings.linkml.yaml > "$tmp"
{
  echo "# GENERATED by scripts/gen_profile_settings.sh from profile_settings.linkml.yaml: do not edit."
  echo "# Change the schema and regenerate."
  cat "$tmp"
} > "$out"
echo "wrote providers/$out"
